// Adopts the UIKit scene-based life cycle on iOS.
//
// Apps built with the iOS 27 SDK (Xcode 27) must create their window from a scene
// delegate; otherwise UIKit stops them at launch with "UIScene life cycle is required for
// apps built with this SDK". Expo SDK 54's template AppDelegate creates the window itself,
// so this plugin, applied on every prebuild:
//   1. adds UIApplicationSceneManifest to Info.plist (single scene, SceneDelegate);
//   2. writes ios/<project>/SceneDelegate.swift and adds it to the app target;
//   3. changes AppDelegate.swift to keep the launch options and leave the window to the
//      scene delegate.
// The scene delegate starts React Native in its window, routes opened URLs and universal
// links to RCTLinkingManager, and forwards the scene's foreground/background events to the
// Expo app delegate (with scenes, UIKit stops calling the app delegate's versions).
const fs = require('fs');
const path = require('path');
const { withInfoPlist, withAppDelegate, withXcodeProject, IOSConfig } = require('expo/config-plugins');

const MARKER = '// withSceneLifecycle';

const SCENE_DELEGATE = `import UIKit
import React
import Expo

// Generated by plugins/withSceneLifecycle.js on every prebuild. Do not edit by hand.
// UIScene life cycle: apps built with the iOS 27 SDK must create their window here.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // A URL that launched the app arrives here rather than in the launch options.
    var launchOptions = appDelegate.launchOptions ?? [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  // Linking API
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  // Universal Links
  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }

  // With scenes, UIKit no longer calls these on the app delegate; Expo modules listen there.
  func sceneDidBecomeActive(_ scene: UIScene) {
    (UIApplication.shared.delegate as? ExpoAppDelegate)?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    (UIApplication.shared.delegate as? ExpoAppDelegate)?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    (UIApplication.shared.delegate as? ExpoAppDelegate)?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    (UIApplication.shared.delegate as? ExpoAppDelegate)?.applicationDidEnterBackground(UIApplication.shared)
  }
}
`;

function withSceneManifest(config) {
  return withInfoPlist(config, (c) => {
    c.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return c;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (c) => {
    if (c.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate');
    }
    let src = c.modResults.contents;
    if (src.includes(MARKER)) return c;

    const windowBlock =
      /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\(\s*\n\s*withModuleName: "main",\s*\n\s*in: window,\s*\n\s*launchOptions: launchOptions\)\s*\n#endif/;
    if (!windowBlock.test(src)) {
      throw new Error('withSceneLifecycle: the AppDelegate window block was not found (Expo template changed?)');
    }
    src = src.replace(
      windowBlock,
      `    ${MARKER}: SceneDelegate creates the window and starts React Native in it\n` +
        `    // (UIScene life cycle, required for apps built with the iOS 27 SDK).\n` +
        `    self.launchOptions = launchOptions`
    );

    const factoryVar = 'var reactNativeFactory: RCTReactNativeFactory?';
    if (!src.includes(factoryVar)) {
      throw new Error('withSceneLifecycle: reactNativeFactory property not found in AppDelegate');
    }
    src = src.replace(
      factoryVar,
      `${factoryVar}\n  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?`
    );
    c.modResults.contents = src;
    return c;
  });
}

function withSceneDelegateFile(config) {
  return withXcodeProject(config, (c) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(c.modRequest.projectRoot);
    const relPath = `${projectName}/SceneDelegate.swift`;
    fs.writeFileSync(path.join(c.modRequest.platformProjectRoot, relPath), SCENE_DELEGATE);
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: relPath,
      groupName: projectName,
      project: c.modResults,
    });
    return c;
  });
}

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  config = withSceneDelegateFile(config);
  return config;
};
